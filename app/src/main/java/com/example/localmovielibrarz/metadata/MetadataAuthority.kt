package com.example.localmovielibrarz.metadata

/**
 * 字段值的权威等级。
 *
 * 为什么需要等级：现有刮削是「后一个来源成功就整条覆盖写库」，用户的修改又和刮削结果共用
 * 同一列，没有等级就无法区分「这条更可信」与「这条不许动」。回退链会把不同质量的值混成一锅，
 * 甚至用站点数据冲掉用户亲手改过的内容。
 *
 * 约定：rank 越大越可信；[canOverride] 只在严格大于时成立。同等级之间没有证据说明谁更新，
 * 允许同等级互相覆盖会让最终结果取决于请求先后顺序（同一部片刮两次可能得到不同标题）。
 * 「旧的为空、新的非空」这个同等级例外属于空值判断，交给 `MetadataMergeEngine` 处理——
 * 枚举只表达等级，不越权替引擎解释「空」。
 */
enum class MetadataAuthority(val rank: Int) {
    /**
     * 来源未知或无法归因。最低级：只适合占位，不允许覆盖任何已有值。
     *
     * 保留这一级而不是让调用方传 null，是为了让「这条数据来路不明」本身也能被记录与审计。
     */
    Unknown(0),

    /**
     * 从文件名推断（番号、年份等）。
     *
     * 低于站点：文件名可以被任意改名，且常混有发布组、画质、站点前缀等噪声，
     * 推断结果只能算线索，站点明确给出的值应当压过它。
     */
    Filename(1),

    /** 刮削站点。默认的自动填充来源，同一部片多个站点结果质量大致同档。 */
    Provider(2),

    /**
     * 库内 `.nfo`。
     *
     * 高于站点：NFO 通常是用户整理过、或本应用上次刮削后人工修正再导出的结果；
     * 让站点覆盖它等于把用户整理的内容冲掉，因此把它放在站点之上、手改之下。
     */
    LocalNfo(3),

    /**
     * 用户在本应用内手改。最高级。
     *
     * 它与其他等级不是简单的「更高所以覆盖」关系：手改值是用户明确表达的结果，自动刮削
     * 即使权威度更低也不该悄悄改掉它，所以 `MetadataMergeEngine` 会返回 NeedsReview 而不是 Apply。
     */
    Manual(4);

    /**
     * 本等级能否自动覆盖 [other]。
     *
     * 严格大于才为 true；同等级返回 false，空值例外由合并引擎判断，避免把「可以填空白」
     * 误实现成「同级可以互相覆盖」。
     */
    fun canOverride(other: MetadataAuthority): Boolean = rank > other.rank
}
